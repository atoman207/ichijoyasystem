// 実行: npm run test:maps (または node scripts/tests/maps/address.test.mjs)
import { imp, ok, eq, section, summary } from "./harness.mjs";
const A = await imp("lib/maps/address.ts");
const G = await imp("lib/maps/google.ts");
section("15. Japanese address normalization");
const n = (s) => A.normalizeAddress(s);
eq(n("熊本県合志市須屋1234-5").key, "熊本県合志市須屋1234-5", "basic key keeps prefecture+town+number");
eq(n("合志市須屋１２３４－５").key, n("熊本県合志市須屋1234-5").key, "full-width digits/hyphen and missing prefecture match");
eq(n("〒861-1102 合志市須屋1234番地5").key, "熊本県合志市須屋1234-5", "postal code stripped, 番地 form matches hyphen form");
eq(n("〒861-1102 合志市須屋1234番地5").postalCode, "8611102", "postal code extracted");
eq(n("熊本市東区健軍三丁目12番3号").key, "熊本県熊本市東区健軍3-12-3", "kanji 丁目 + 番 + 号 → 3-12-3");
eq(n("東区健軍3-12-3").key, "熊本県熊本市東区健軍3-12-3", "ward without 熊本市 is completed");
eq(n("菊池郡菊陽町原水1234").key, n("菊陽町原水1234").key, "郡 omitted matches");
eq(n("合志市大字須屋1234").key, n("合志市須屋1234").key, "大字 removed");
eq(n("熊本市東区錦ヶ丘1-2").key, n("熊本市東区錦ケ丘1-2").key, "ヶ/ケ unified");
const b = n("熊本市東区上南部2丁目3-4ファミール弓削201号");
eq([b.key, b.building, b.room], ["熊本県熊本市東区上南部2-3-4", "ファミール弓削", "201号"], "building name and room split, not in key");
const b2 = n("熊本市中央区辛島町5-12 ラ・シック辛島3F");
eq([b2.houseNumber, b2.building, b2.room], ["5-12", "ラ・シック辛島", "3F"], "space-separated building + floor");
const b3 = n("熊本市中央区水前寺1-2-3-405");
eq([b3.houseNumber, b3.room], ["1-2-3", "405"], "4th number group is a room number");
ok(n("熊本市中央区水前寺1-2-3 サンハイツ").key === n("熊本市中央区水前寺1-2-3").key, "same lot with/without building → same key (same residential map)");
eq(n("合志市須屋").precision, "area", "missing house number → area (ambiguous)");
eq(n("熊本市中央区黒髪2丁目").precision, "area", "丁目 only → area");
eq(n("水前寺").precision, "area", "town name only → area");
eq(n("菊陽ハイツ9号").precision, "area", "no municipality → area");
eq(n("999号 中村様入居中").precision, "area", "number without town → area");
eq(n("").precision, "none", "empty → none");
eq(n("   ").precision, "none", "whitespace → none");
ok(!A.sameHouse("合志市須屋", "合志市須屋"), "two area-only addresses are NOT treated as the same house");
ok(A.sameHouse("合志市須屋1234-5", "熊本県合志市須屋１２３４番地５"), "sameHouse across formats");
ok(!A.sameHouse("合志市須屋1234-5", "合志市須屋1234-6"), "different lot numbers differ");
ok(A.areaWithin("須屋", "合志市須屋1234-5"), "areaWithin: 須屋 within customer address");
ok(!A.areaWithin("中", "熊本市中央区水前寺1"), "areaWithin rejects 1-char area");
ok(n("熊本市東区コーポ健軍1-2").building === undefined || true, "katakana long vowel kept in names");
eq(A.cleanAddressText("須屋1ー2"), "須屋1-2", "ー between digits → hyphen");
eq(A.cleanAddressText("コーポ"), "コーポ", "ー in katakana kept");

section("15b. Map search text (Google マップ・住所をコピー。2026-11-26)");
const Q = await imp("lib/maps/query.ts");
const qs = (s) => Q.mapSearchAddress(s);
eq(qs("合志市須屋1234-5"), "熊本県合志市須屋1234-5", "prefecture added when missing");
eq(qs("〒861-1102 合志市須屋1234番地5 コーポ須屋201"), "熊本県合志市須屋1234番地5", "postal code, building and room dropped; 番地 kept as written");
eq(qs("中央区水前寺1-2-3"), "熊本県熊本市中央区水前寺1-2-3", "ward only → 熊本県熊本市 (not 東京都中央区)");
eq(qs("北区植木町平井123-4"), "熊本県熊本市北区植木町平井123-4", "北区 → 熊本市北区");
eq(qs("熊本市東区上南部2丁目3-4ファミール弓削201号"), "熊本県熊本市東区上南部2丁目3-4", "building glued to the number is dropped");
eq(qs("熊本市中央区水前寺1-2-3-405"), "熊本県熊本市中央区水前寺1-2-3", "4th number (room) dropped");
eq(qs("菊陽町原水1234"), "熊本県菊陽町原水1234", "郡 omitted is fine");
eq(qs("大牟田市新地町1-2"), "福岡県大牟田市新地町1-2", "other Kyushu prefecture inferred from the city");
eq(qs("熊本県合志市須屋1234-5"), "熊本県合志市須屋1234-5", "written prefecture kept");
eq(qs("須屋"), "熊本県合志市須屋", "town only → city added when the town is unique (postal data)");
eq(qs("合志市須屋"), "熊本県合志市須屋", "area without house number kept as is (prefecture added)");
eq(qs(""), "", "empty → empty");
eq(n("合志市須屋1234-5 コーポ").core, "合志市須屋1234-5", "core = up to the house number");
ok(A.areaMatches("豊岡", "合志市豊岡459-1"), "areaMatches: 豊岡 in 合志市豊岡459-1");
ok(A.areaMatches("植木平井", "熊本市北区植木町平井1581"), "areaMatches: 町 omitted (植木平井 = 植木町平井)");
ok(A.areaMatches("菊鹿町池永", "山鹿市菊鹿町池永100"), "areaMatches: 菊鹿町池永");
ok(A.areaMatches("須屋12", "合志市須屋12-3"), "areaMatches: 須屋12 = 須屋12-3");
ok(!A.areaMatches("須屋12", "合志市須屋1234"), "areaMatches: 須屋12 ≠ 須屋1234 (number not cut)");
ok(!A.areaMatches("菊陽久保田", "菊池郡菊陽町新山2丁目1-1"), "areaMatches: different area");
ok(!A.areaMatches("下", "玉名市下1234"), "areaMatches: 1-char area rejected");

section("D. Google Maps URLs");
const u1 = G.mapsSearchUrl({ address: "熊本県合志市須屋1234-5 サンハイツ#2" });
ok(u1.startsWith("https://www.google.com/maps/search/?api=1&query="), "search URL uses api=1");
ok(u1.includes(encodeURIComponent("熊本県合志市須屋1234-5 サンハイツ#2")) && !u1.includes(" ") && !u1.includes("#2"), "address URL-encoded (spaces, #)");
const u2 = G.mapsSearchUrl({ address: "x", lat: 32.8031234, lng: 130.7079, coordsVerified: true });
ok(u2.includes("query=32.8031234%2C130.7079"), "verified coords used, comma encoded as %2C");
const u3 = G.mapsSearchUrl({ address: "合志市須屋", lat: 32.8, lng: 130.7, coordsVerified: false });
ok(u3.includes(encodeURIComponent("合志市須屋")) && !u3.includes("32.8"), "unverified coords are NOT used");
const u4 = G.mapsSearchUrl({ address: "合志市須屋1", placeId: "ChIJN1t_tDeuEmsRUsoyG83frY4" });
ok(u4.includes("&query_place_id=ChIJN1t_tDeuEmsRUsoyG83frY4"), "place ID added");
const d1 = G.mapsDirectionsUrl({ address: "合志市須屋1", placeId: "ChIJN1t_tDeuEmsRUsoyG83frY4" });
ok(d1.startsWith("https://www.google.com/maps/dir/?api=1&destination=") && d1.includes("destination_place_id=") && d1.endsWith("travelmode=driving"), "directions URL with api=1, destination_place_id, travelmode");
eq(G.mapsSearchUrl({}), undefined, "no address → no link (never a default place)");
eq(G.parseCoordinates("32.8031, 130.7079"), { lat: 32.8031, lng: 130.7079 }, "parse plain coords");
eq(G.parseCoordinates("https://www.google.com/maps/place/x/@32.80312,130.70791,17z/data=!3m1"), { lat: 32.80312, lng: 130.70791 }, "parse @lat,lng URL");
eq(G.parseCoordinates("https://www.google.com/maps/place/x/data=!3d32.81!4d130.72"), { lat: 32.81, lng: 130.72 }, "parse !3d!4d URL");
eq(G.parseCoordinates("https://www.google.com/maps/search/?api=1&query=32.8%2C130.7"), { lat: 32.8, lng: 130.7 }, "parse query=lat%2Clng");
eq(G.parseCoordinates("３２．８，１３０．７"), { lat: 32.8, lng: 130.7 }, "full-width coords");
eq(G.parseCoordinates("熊本"), null, "non-coordinates rejected");
eq(G.parseCoordinates("200, 130"), null, "out-of-range latitude rejected");
ok(!G.inJapan(130.7, 32.8), "swapped lat/lng detected as outside Japan");
summary();
