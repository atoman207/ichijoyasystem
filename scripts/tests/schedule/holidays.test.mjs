eq([sum.sundays, sum.holidays, sum.others], [4, 2, 3], "2031 年: 日曜 4・祝日 2 (元日・成人の日)・その他 (年末 12/29〜31) 3");
eq(sum.closed, 9, "合計 9 日");
ok(sum.emptyMonths.includes(2) && !sum.emptyMonths.includes(1), "休業日のない月");

