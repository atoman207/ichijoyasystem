section("まとめて登録");
db.holidays = [];
const rule = (o) => HC.readClosedDayRule((k) => (k in o ? (Array.isArray(o[k]) ? o[k][0] : o[k]) : null), (k) => (Array.isArray(o[k]) ? o[k] : o[k] ? [o[k]] : []));
ok("error" in rule({ from: "2031-01-01", to: "2031-12-31" }), "条件がないと断る");
ok("error" in rule({ from: "2031-01-01", to: "2034-12-31", weekday: "0" }), "3 年を超える期間は断る");
ok("error" in rule({ from: "2031-12-31", to: "2031-01-01", weekday: "0" }), "終了日が開始日より前は断る");
ok("error" in rule({ from: "2031-01-01", to: "2031-12-31", altSaturday: "2031-01-03" }), "隔週の基準日が土曜でないと断る");
const r1 = rule({ from: "2031-01-01", to: "2031-01-31", weekday: ["0"], altSaturday: "2031-01-04", holidays: "1", label: "" });
ok(!("error" in r1), "条件を読める");
const p1 = HC.planClosedDays(db, r1);
// 2031-01: 日曜 5・12・19・26、隔週の土曜 4・18、祝日 1 (元日)・13 (成人の日)
eq(p1.add.map((a) => a.date.slice(8)), ["01", "04", "05", "12", "13", "18", "19", "26"], "日曜・隔週の土曜・祝日");
eq(p1.add.find((a) => a.date === "2031-01-13")?.reason, "成人の日", "祝日は名前を理由にする");
eq(HC.applyClosedDayPlan(db, p1), 8, "8 日を登録");
ok(CAP.isClosedDay(db, "2031-01-18") && !CAP.isClosedDay(db, "2031-01-11"), "隔週の土曜だけ休業日");
eq(HC.planClosedDays(db, r1).add.length, 0, "2 回目は追加なし");
eq(HC.planClosedDays(db, r1).unchanged, 8, "すでに休業日の日を数える");
const r2 = rule({ from: "2031-12-29", to: "2032-01-03", allDays: "1", label: "年末年始" });
const p2 = HC.planClosedDays(db, r2);
eq(p2.add.length, 6, "期間のすべての日 (年末年始 6 日)");
HC.applyClosedDayPlan(db, p2);
eq(db.holidays.find((h) => h.date === "2032-01-02")?.label, "年末年始", "名前を付ける");
const r3 = rule({ from: "2031-01-01", to: "2031-01-31", weekday: ["6"], altSaturday: "2031-01-04", mode: "remove" });
const p3 = HC.planClosedDays(db, r3);
eq(p3.remove.map((h) => h.date.slice(8)), ["04", "18"], "毎週の土曜を選ぶと隔週は使わず、休業日の土曜だけを外す");
eq(p3.unchanged, 2, "休業日でない土曜は変更なし");
HC.applyClosedDayPlan(db, p3);
ok(!CAP.isClosedDay(db, "2031-01-04"), "外した土曜は営業日");
eq(HC.describeRule(r1), "2031-01-01〜2031-01-31 の 毎週 日曜・隔週の土曜 (2031-01-04 から)・祝日", "条件の説明");
const back = rule(Object.fromEntries(Object.entries(HC.ruleParams(r1).reduce((m, [k, v]) => ((m[k] ??= []).push(v), m), {}))));
eq(back, r1, "隠しフィールドから同じ条件に戻る");

