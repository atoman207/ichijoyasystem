/**
 * データベース定義 (Supabase / PostgreSQL)
 * ------------------------------------------------------------
 * - アプリのコレクション (src/lib/db/types.ts の Database) と PostgreSQL のテーブルの対応表
 * - phase1/database/schema.sql はこの定義から生成する (node scripts/import/generate-schema.mjs)
 * - 列名は camelCase のフィールド名を snake_case にしたもの。配列・入れ子は jsonb / text[]
 * - 循環する参照 (問い合わせ ⇄ 見積、受注 ⇄ 請求) は片方向のみ外部キーにする
 *
 * このファイルは Node のスクリプトからも読み込むため、パスエイリアス (@/) や型以外の import を使わない。
 */

export interface TableDef {
  /** Database のコレクション名 */
  collection: string;
  /** PostgreSQL のテーブル名 */
  table: string;
  /** 日本語の名前 (設計書用) */
  label: string;
  /** [フィールド名 (camelCase), 型と制約] */
  columns: [string, string][];
  /** 読み込み時の並び順 (列名) */
  orderBy: string[];
  indexes?: string[][];
}

/**
 * 読み込み時の並び順 (orderBy + id)。ページごとに読むため、同じ値の行があっても順序が一意になるよう id を最後に加える。
 * この並びの索引も作る (schema-sql.mjs)。索引がないと行数が増えたときに並べ替えが時間切れになる
 */
export function loadOrder(def: TableDef): string[] {
  return def.orderBy.includes("id") || !def.columns.some(([f]) => f === "id") ? def.orderBy : [...def.orderBy, "id"];
}

