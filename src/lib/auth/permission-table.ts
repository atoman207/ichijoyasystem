/**
 * 権限一覧 (設定 → ユーザーと権限 に表示)
 * ------------------------------------------------------------
 * 実際の判定は src/lib/auth/permissions.ts の関数で行う。この表はその内容を利用者向けに書いたもの
 * (Phase 1 の「権限設定一覧」に、第 2〜第 4 段階で追加した操作を加えている)。判定を変えたときはこの表も直す。
 * 閲覧の範囲の設定 (src/lib/access-policy.ts) で変わる行は key を付け、permissionTable(設定) で設定どおりの文と欄にする。
 * ○ = 全店舗 / 自店 = 所属店舗の情報のみ / 本人 = 自分が登録・申請したもののみ / 閲覧 = 見るだけ / − = できない
 */

import { DEFAULT_ACCESS_POLICY, type AccessPolicy } from "@/lib/access-policy";

export type Cell = "○" | "自店" | "本人" | "閲覧" | "−";

export interface PermissionRow {
  group: string;
  action: string;
  admin: Cell;
  hq: Cell;
  manager: Cell;
  staff: Cell;
  /** 第 2 段階以降に追加した操作 */
  added?: boolean;
  /** 閲覧の範囲の設定 (src/lib/access-policy.ts) で変わる行 */
  key?: PolicyRowKey;
}

type PolicyRowKey = "customers" | "maps" | "openCases" | "closedCases" | "viewApprove" | "viewLog" | "reports" | "mgmt" | "kpi" | "surveyCompare" | "promo";

const r = (group: string, action: string, admin: Cell, hq: Cell, manager: Cell, staff: Cell, added = false, key?: PolicyRowKey): PermissionRow => ({ group, action, admin, hq, manager, staff, added, ...(key ? { key } : {}) });

/** 閲覧の範囲の設定ごとの行 (操作の文と、店長・店舗スタッフの欄) */
function policyRow(row: PermissionRow, p: Pick<AccessPolicy, "figures" | "customers" | "grantDays">): PermissionRow {
  const allFig = p.figures === "all";
  const cust = p.customers;
  const set = (action: string, manager: Cell, staff: Cell): PermissionRow => ({ ...row, action, manager, staff });
  switch (row.key) {
    // 店長は顧客・問い合わせ・見積・受注を全店舗で変更できる (canEditCaseStore) ので、閲覧の範囲の設定に関わらず全店舗 (請求書は設定どおり)
    case "customers":
      return cust === "all"
        ? set("顧客・問い合わせ・見積・受注・請求書・写真・施工の履歴の閲覧 (ほかの店舗の記録は閲覧のみ。店長は顧客・問い合わせ・見積・受注を変更もできる。閲覧は変更履歴に記録)", "○", "○")
        : cust === "approval"
          ? set("顧客・問い合わせ・見積・受注・請求書の閲覧 (店長はほかの店舗も見られる。顧客・問い合わせ・見積・受注は変更もできる)", "○", "自店")
          : set("顧客・問い合わせ・見積・受注・請求書の閲覧 (店長は顧客・問い合わせ・見積・受注を全店舗。請求書は自店舗)", "○", "自店");
    // 地図・住宅地図の表示は記録の閲覧と同じ (src/lib/maps/access.ts。登録・差し替え・位置の修正は記録を変更できる人だけ)
    case "maps":
      return cust === "all"
        ? set("Google マップのリンク・住宅地図 (PDF) の表示 (顧客・案件を見られる人と予定の担当者。ほかの店舗の記録は閲覧のみ。閲覧は変更履歴に記録)", "○", "○")
        : set("Google マップのリンク・住宅地図 (PDF) の表示 (顧客・案件を見られる人と予定の担当者。店舗スタッフは自店と、記録を見られるほかの店舗の案件 (閲覧のみ)。閲覧は変更履歴に記録)", "○", "自店");
    case "openCases":
      return set(row.action, "○", cust === "all" ? "○" : "閲覧");
    case "closedCases":
      return cust === "all"
        ? set("ほかの店舗の完了した案件 (入金完了・全処理完了・失注) のお客様の閲覧 (閲覧のみ。店長は変更もできる)", "○", "○")
        : cust === "approval"
          ? set(`ほかの店舗の完了した案件のお客様の閲覧 (店舗スタッフは「閲覧の申請」→ 所属店舗の店長の承認から ${p.grantDays} 日、閲覧のみ)`, "○", "本人")
          : set("ほかの店舗の完了した案件のお客様の閲覧 (店長は顧客・問い合わせ・見積・受注を全店舗で変更できるため見られる)", "○", "−");
    case "viewApprove":
      return set(cust === "approval" ? "顧客情報の閲覧の申請の承認 (店長は所属店舗のスタッフの申請)" : "顧客情報の閲覧の申請の承認 (閲覧の範囲が承認制のときだけ使う)", cust === "approval" ? "自店" : "−", "−");
    case "reports":
      return set(allFig ? "レポート・分析 (経営ダッシュボード。全店舗の数字を閲覧)" : "レポート・分析 (経営ダッシュボード)", allFig ? "○" : "自店", allFig ? "○" : "−");
    case "mgmt":
      return set(allFig ? "管理会計の閲覧 (店舗別損益・内部受注・材料原価・在庫。全店舗。登録・設定・確定は本部・管理者)" : "管理会計の閲覧 (店舗別損益・内部受注・材料原価・在庫。登録・設定・確定は本部・管理者)", allFig ? "○" : "自店", allFig ? "○" : "−");
    case "kpi":
      return set(allFig ? "KPI の閲覧 (店舗別・全社の返信率・評価・クレーム率・口コミは全店舗。社員別は管理者・本部は全員、店長は自店の社員、スタッフは本人)" : row.action, allFig ? "○" : "自店", allFig ? "○" : "自店");
    case "surveyCompare":
      return set(allFig ? "アンケートの年度ごとの比較 (過去の集計表とシステムの回答。全店舗)" : row.action, allFig ? "○" : "自店", allFig ? "○" : "自店");
    case "promo":
      return set(row.action, allFig ? "○" : "自店", allFig ? "○" : "−");
    default:
      return row;
  }
}

